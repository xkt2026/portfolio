#!/usr/bin/env node
/**
 * Case-study pipeline, step 1 (`docs/NEXT_LEVEL_PAGES.md`).
 *
 * `/project/<slug>` carries a five-frame `[Imgaeproject]` column that the homepage
 * never loads, so the images have to be captured per project. Everything about that
 * capture is mechanical, so this script does it:
 *
 *   1. read the 19 slugs straight out of `data.ts` (the content seam)
 *   2. fetch each case-study page
 *   3. take the `framerusercontent` images inside `[Imgaeproject]`, in DOM order —
 *      the region ends at `[next]`, which keeps the favicon and OG images out
 *   4. download them into the shared asset folder (existing files are skipped)
 *   5. write the generated image seam `galleries.ts` + a JSON record for the docs
 *
 *   node scripts/fetch-project-galleries.mjs              # every slug
 *   node scripts/fetch-project-galleries.mjs dafi fromanother
 *
 * Re-running is safe and cheap: finished images are not downloaded twice.
 */
import { readFile, writeFile, mkdir, stat } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const ORIGIN = "https://huyml.co";
const ROOT = path.resolve(import.meta.dirname, "..");
const REL = "src/components/sites/huyml-co-eb36a18b/root-8a5edab2";
const DATA = path.join(ROOT, REL, "data.ts");
const OUT_TS = path.join(ROOT, REL, "galleries.ts");
const OUT_RESEARCH = path.join(ROOT, "docs/research/huyml-co-eb36a18b/galleries.json");
const OUT_IMAGES = path.join(ROOT, "public/sites/huyml-co-eb36a18b/shared");

/** The CDN honours `scale-down-to`; the column renders at 45% of the viewport. */
const SCALE_DOWN = 1600;
const CONCURRENCY = 4;
const TIMEOUT_MS = 30_000;

const IMAGE_RE = /https:\/\/framerusercontent\.com\/images\/([A-Za-z0-9_.\-]+)/g;

async function exists(file) {
  try {
    await stat(file);
    return true;
  } catch {
    return false;
  }
}

async function getText(url) {
  const res = await fetch(url, { signal: AbortSignal.timeout(TIMEOUT_MS) });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.text();
}

async function getBuffer(url) {
  const res = await fetch(url, { signal: AbortSignal.timeout(TIMEOUT_MS) });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return Buffer.from(await res.arrayBuffer());
}

/** JPEG / PNG / WebP / GIF magic bytes — a 200 response is not enough to trust a CDN. */
function isImageBuffer(file, buf) {
  if (buf.length < 12) return false;
  if (/\.jpe?g$/i.test(file)) return buf[0] === 0xff && buf[1] === 0xd8;
  if (/\.png$/i.test(file)) return buf.subarray(0, 4).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47]));
  if (/\.webp$/i.test(file)) {
    return buf.subarray(0, 4).toString("latin1") === "RIFF";
  }
  if (/\.gif$/i.test(file)) return buf.subarray(0, 3).toString("latin1") === "GIF";
  return false;
}

/** The slugs live in `ARCHIVE`, and `slug` appears nowhere else in the data file. */
async function readSlugs() {
  const source = await readFile(DATA, "utf8");
  return [...source.matchAll(/"slug":\s*"([^"]+)"/g)].map((match) => match[1]);
}

async function galleryOf(slug) {
  const html = await getText(`${ORIGIN}/project/${slug}`);
  const start = html.indexOf('data-framer-name="Imgaeproject"');
  if (start === -1) throw new Error("no [Imgaeproject] region");
  const next = html.indexOf('data-framer-name="next"', start);
  const region = html.slice(start, next === -1 ? undefined : next);

  const files = [];
  for (const match of region.matchAll(IMAGE_RE)) {
    if (!files.includes(match[1])) files.push(match[1]);
  }
  return files;
}

async function download(file) {
  const dest = path.join(OUT_IMAGES, file);
  if (await exists(dest)) return "cached";
  const buf = await getBuffer(
    `https://framerusercontent.com/images/${file}?scale-down-to=${SCALE_DOWN}`,
  );
  if (!isImageBuffer(file, buf)) throw new Error(`not an image (${buf.length}B)`);
  await writeFile(dest, buf);
  return `${Math.round(buf.length / 1024)}kB`;
}

async function pool(items, limit, worker) {
  const results = new Array(items.length);
  let cursor = 0;
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (cursor < items.length) {
        const index = cursor++;
        results[index] = await worker(items[index]);
      }
    }),
  );
  return results;
}

function writeGalleries(galleries) {
  const body = Object.entries(galleries)
    .map(([slug, files]) => {
      const list = files.map((file) => `"${file}"`).join(", ");
      return `  "${slug}": [${list}],`;
    })
    .join("\n");

  const source = `/**
 * GENERATED by \`scripts/fetch-project-galleries.mjs\` — do not hand-edit.
 *
 * The image half of the case-study content seam: \`data.ts\` owns the words,
 * this file owns the pictures. Each entry lists the images of the live
 * \`[Imgaeproject]\` column in scroll order, as filenames inside
 * \`public/sites/huyml-co-eb36a18b/shared/\` (resolve them with \`assetUrl\`).
 *
 * Re-run the script after adding a project, or replace the files with your own
 * artwork and keep the names — the page renders \`gallery.length\` frames.
 */
export const PROJECT_GALLERIES: Readonly<Record<string, readonly string[]>> = {
${body}
};
`;
  return source;
}

async function main() {
  const requested = process.argv.slice(2);
  const slugs = requested.length > 0 ? requested : await readSlugs();
  await mkdir(OUT_IMAGES, { recursive: true });

  console.log(`capturing ${slugs.length} case stud${slugs.length === 1 ? "y" : "ies"}`);
  const galleries = {};
  const failures = [];

  await pool(slugs, CONCURRENCY, async (slug) => {
    try {
      const files = await galleryOf(slug);
      const notes = [];
      for (const file of files) notes.push(await download(file));
      galleries[slug] = files;
      console.log(`  ${slug.padEnd(22)} ${files.length} images (${notes.join(", ")})`);
    } catch (error) {
      failures.push(`${slug}: ${error.message}`);
      console.log(`  ${slug.padEnd(22)} FAILED — ${error.message}`);
    }
  });

  await writeFile(OUT_TS, writeGalleries(galleries));
  await writeFile(OUT_RESEARCH, `${JSON.stringify(galleries, null, 2)}\n`);
  console.log(`wrote ${path.relative(ROOT, OUT_TS)} and ${path.relative(ROOT, OUT_RESEARCH)}`);
  if (failures.length > 0) {
    console.log(`\n${failures.length} failed:`);
    for (const failure of failures) console.log(`  ${failure}`);
    process.exitCode = 1;
  }
}

await main();
